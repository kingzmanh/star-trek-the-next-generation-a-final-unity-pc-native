"""Write the Miles AIL native mappings into tools/native_<mod>.txt (between
the "# --- AIL" marker and the end of the file), from tools/ail_api.py.
usage: gen_ail_natives.py   (every program in port.json)"""
import os, sys, subprocess
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
T = os.path.dirname(os.path.abspath(__file__))
import json
_P = json.load(open(os.path.join(T, '..', 'port.json')))
MODS = [(m['tag'], os.path.splitext(m['exe'])[0]) for m in _P['programs']]
SAME = '''install_DIG_INI uninstall_DIG_driver allocate_sample_handle release_sample_handle init_sample
set_sample_file allocate_file_sample set_sample_address set_sample_type start_sample stop_sample
resume_sample end_sample set_sample_playback_rate set_sample_volume set_sample_pan set_sample_loop_count
sample_status sample_playback_rate sample_volume sample_pan sample_loop_count set_digital_master_volume
digital_master_volume minimum_sample_buffer_size sample_buffer_ready load_sample_buffer
set_sample_position sample_position register_SOB_callback register_EOB_callback register_EOS_callback
set_sample_user_data sample_user_data active_sample_count install_MDI_INI uninstall_MDI_driver
MDI_driver_type allocate_sequence_handle release_sequence_handle init_sequence start_sequence
stop_sequence resume_sequence end_sequence set_sequence_tempo set_sequence_volume set_sequence_loop_count
sequence_status sequence_tempo sequence_volume sequence_loop_count set_XMIDI_master_volume
XMIDI_master_volume active_sequence_count controller_value sequence_position branch_index
register_prefix_callback register_trigger_callback register_sequence_callback register_beat_callback
register_event_callback register_timbre_callback set_sequence_user_data sequence_user_data
lock_channel release_channel map_sequence_channel true_sequence_channel send_channel_voice_message
send_sysex_message'''.split()
MAP = {'AIL_' + n: 'N_AIL_' + n for n in SAME}
MAP.update({
    'AIL_install_DIG_driver_file': 'N_AIL_install_DIG_driver', 'AIL_install_DIG_driver_image': 'N_AIL_install_DIG_driver',
    'AIL_install_MDI_driver_file': 'N_AIL_install_MDI_driver', 'AIL_install_MDI_driver_image': 'N_AIL_install_MDI_driver',
    'AIL_register_EOF_callback': 'N_AIL_ret0', 'AIL_set_GTL_filename_prefix': 'N_AIL_nop',
    'AIL_timbre_status': 'N_AIL_ret1', 'AIL_install_timbre': 'N_AIL_nop', 'AIL_protect_timbre': 'N_AIL_nop',
    'AIL_unprotect_timbre': 'N_AIL_nop', 'AIL_channel_notes': 'N_AIL_ret0', 'AIL_register_ICA_array': 'N_AIL_nop',
    'AIL_create_wave_synthesizer': 'N_AIL_ret0', 'AIL_destroy_wave_synthesizer': 'N_AIL_nop',
})
for mod, exe in MODS:
    out = subprocess.run([sys.executable, os.path.join(T, 'ail_api.py'), os.path.join(T, '..', 'gamedata', 'cd', exe + '.EXE')],
                         capture_output=True, text=True).stdout
    lines, seen = [], {}
    for l in out.splitlines():
        a, name = l.split()
        if name not in MAP:
            continue
        if a in seen and seen[a] != MAP[name]:
            print('%s: %s shared by %s and %s - skipped' % (mod, a, seen[a], name))
            continue
        if a in seen:
            continue
        seen[a] = MAP[name]
        lines.append('%s %s   # %s' % (a, MAP[name], name))
    fn = os.path.join(T, 'native_%s.txt' % mod)
    txt = open(fn).read()
    k = txt.find('# --- AIL')
    if k >= 0:
        txt = txt[:k]
    txt = txt.rstrip('\n') + '\n# --- AIL (generated by tools/gen_ail_natives.py) ---\n' + '\n'.join(lines) + '\n'
    open(fn, 'w').write(txt)
    missing = sorted(set(MAP) - set(n for l in out.splitlines() for n in [l.split()[1]]))
    print(mod, len(lines), 'mapped; not found:', ' '.join(missing))
